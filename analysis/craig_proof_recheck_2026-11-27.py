# ---------- SU(5) representations ----------
def rand_su(n, scale=1.0):
    a = rng.normal(size=(n, n)) + 1j*rng.normal(size=(n, n))
    h = (a + a.conj().T)/2; h -= np.trace(h)/n*np.eye(n)
