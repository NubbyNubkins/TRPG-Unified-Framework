pairs = list(itertools.combinations(range(5), 2))
def wedge2(m):           # action on antisymmetric tensors (the 10) of a group element
    return np.array([[m[i, k]*m[j, l] - m[i, l]*m[j, k] for (k, l) in pairs] for (i, j) in pairs])
def wedge2_alg(x):       # Lie-algebra action on the 10
    e = np.eye(5); return np.array([[x[i, k]*e[j, l] + e[i, k]*x[j, l] - x[i, l]*e[j, k] - e[i, l]*x[j, k]
                                      for (k, l) in pairs] for (i, j) in pairs])
def blocks(*ms):
    n = sum(m.shape[0] for m in ms); r = np.zeros((n, n), complex); i = 0
    for m in ms: k = m.shape[0]; r[i:i+k, i:i+k] = m; i += k
    return r
